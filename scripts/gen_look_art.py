"""Writes src/data/lookArt.ts from public/assets/look.json (ART10): tint and swatch colors, accessory attach points.
Run it again whenever the art chat changes look.json (a unit test fails when the two disagree)."""
import json

L = json.load(open('public/assets/look.json'))
hx = lambda s: '0x' + s[1:].lower()
def table(rows): return '{ ' + ', '.join(f"{r['id']}: {{ tint: {hx(r['tint'])}, base: {hx(r['base'])} }}" for r in rows) + ' }'
out = ["// GENERATED by scripts/gen_look_art.py from public/assets/look.json (ART10). Do not edit by hand.",
       "export interface Tint { tint: number; base: number }",
       f"export const SKIN_TINTS: readonly Tint[] = [{', '.join(f'{{ tint: {hx(r['tint'])}, base: {hx(r['base'])} }}' for r in L['colors']['skin'])}];",
       f"export const ORC_SKIN_TINTS: readonly Tint[] = [{', '.join(f'{{ tint: {hx(r['tint'])}, base: {hx(r['base'])} }}' for r in L['colors']['skinOrc'])}];",
       f"export const HAIR_TINTS: Record<string, Tint> = {table(L['colors']['hair'] + L['colors']['hairShop'])};",
       f"export const CLOTH_TINTS: Record<string, Tint> = {table(L['colors']['dye'] + L['colors']['dyeShop'])};",
       "export interface CosmeticArt { slot: 'head' | 'back' | 'extra'; point: 'head' | 'back' | 'neck' | 'shoulder'; frames: number; icon: string }",
       "export const COSMETIC_ART: Record<string, CosmeticArt> = {"]
for k, v in L['cosmetics'].items():
    out.append(f"  {k}: {{ slot: '{v['slot']}', point: '{v['point']}', frames: {v['frames']}, icon: '{v['icon']}' }},")
out.append("};")
open('src/data/lookArt.ts', 'w').write('\n'.join(out) + '\n')
