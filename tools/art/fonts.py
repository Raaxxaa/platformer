CHARSET = [chr(c) for c in range(32, 127)] + list('×·−—±←↑→↓▸★…')

FONTS = {   # name: (scale, outline, lineHeight, base, size, wrap width)
    'rb_small': (1, True, 11, 7, 7, 256),
    'rb_small_plain': (1, False, 10, 7, 7, 256),
    'rb_large': (2, True, 22, 14, 14, 512),
}


def glyph_array(ch, scale):
    rows = GLYPHS[ch]
    a = np.array([[c == '#' for c in r] for r in rows], bool)
    if scale > 1:
        a = a.repeat(scale, axis=0).repeat(scale, axis=1)
    return a


def _render(ch, scale, outline):
    a = glyph_array(ch, scale)
    h, w = a.shape
    if not outline:
        img = np.zeros((h, w, 4), np.uint8)
        img[a] = (255, 255, 255, 255)
        return img
    pad = np.zeros((h + 2, w + 2), bool)
    pad[1:-1, 1:-1] = a
    ring = np.zeros_like(pad)
    for dy in (-1, 0, 1):
        for dx in (-1, 0, 1):
            ring |= np.roll(np.roll(pad, dy, 0), dx, 1)
    img = np.zeros((h + 2, w + 2, 4), np.uint8)
    img[ring & ~pad] = INK + (255,)
    img[pad] = (255, 255, 255, 255)
    return img


def build_font(name, out_dir):
    scale, outline, line_h, base, size, wrap = FONTS[name]
    gap_letter = scale                               # letter gap 1 (large: 2)
    imgs = {ch: _render(ch, scale, outline) for ch in CHARSET}
    x = y = 0
    row_h = max(im.shape[0] for im in imgs.values())
    place = {}
    for ch in CHARSET:
        h, w = imgs[ch].shape[:2]
        if x + w > wrap:
            x, y = 0, y + row_h + 1
        place[ch] = (x, y)
        x += w + 1
    sheet = np.zeros((y + row_h, wrap, 4), np.uint8)
    chars = []
    for ch in CHARSET:
        im = imgs[ch]
        h, w = im.shape[:2]
        px, py = place[ch]
        sheet[py:py + h, px:px + w] = im
        gw = len(GLYPHS[ch][0]) * scale
        if ch == ' ':
            adv = 4 * scale
        elif ch.isdigit():
            adv = 6 * scale
        else:
            adv = gw + gap_letter
        off = -1 if outline else 0
        chars.append(f'    <char id="{ord(ch)}" x="{px}" y="{py}" width="{w}" height="{h}" xoffset="{off}" '
                     f'yoffset="{off}" xadvance="{adv}" page="0" chnl="15"/>')
    Image.fromarray(sheet, 'RGBA').save(os.path.join(out_dir, name + '.png'))
    xml = ['<?xml version="1.0"?>', '<font>',
           f'  <info face="{name}" size="{size}" bold="0" italic="0" charset="" unicode="1" stretchH="100" '
           f'smooth="0" aa="1" padding="0,0,0,0" spacing="1,1"/>',
           f'  <common lineHeight="{line_h}" base="{base}" scaleW="{wrap}" scaleH="{sheet.shape[0]}" pages="1" '
           f'packed="0"/>',
           '  <pages>', f'    <page id="0" file="{name}.png"/>', '  </pages>',
           f'  <chars count="{len(CHARSET)}">'] + chars + ['  </chars>', '</font>', '']
    with open(os.path.join(out_dir, name + '.xml'), 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(xml))


def build(out_dir):
    os.makedirs(out_dir, exist_ok=True)
    for name in FONTS:
        build_font(name, out_dir)


def sample(path, text='RUSHBLADE 0123456789 1:52.47', scale=3):
    """Preview: the text in all three fonts on a dark panel."""
    lines = []
    for name in ('rb_small', 'rb_small_plain', 'rb_large'):
        sc, outline, *_ = FONTS[name]
        parts = []
        for ch in text:
            im = _render(ch, sc, outline)
            parts.append(im)
            gap = 6 * sc - (len(GLYPHS[ch][0]) * sc) if ch.isdigit() else (sc if ch != ' ' else 4 * sc - 3 * sc)
            parts.append(np.zeros((im.shape[0], max(0, gap - (2 if outline else 0)), 4), np.uint8))
        hgt = max(p.shape[0] for p in parts)
        parts = [np.pad(p, ((0, hgt - p.shape[0]), (0, 0), (0, 0))) for p in parts]
        lines.append(np.concatenate(parts, axis=1))
    W = max(l.shape[1] for l in lines) + 8
    H = sum(l.shape[0] + 4 for l in lines) + 4
    out = Image.new('RGBA', (W, H), (0x1b, 0x18, 0x26, 255))
    y = 4
    for l in lines:
        out.alpha_composite(Image.fromarray(l, 'RGBA'), (4, y))
        y += l.shape[0] + 4
    out.resize((W * scale, H * scale), Image.NEAREST).save(path)
