def _g(rows):
    """'#..#/....' rows, top-aligned in a 9-row cell (7 cap rows + 2 descender rows)."""
    r = rows.split('/')
    w = len(r[0])
    assert all(len(x) == w for x in r), rows
    return r + ['.' * w] * (9 - len(r))


